export function getRamadanDaySchedule(rozaNumber: number = 1): RamadanDaySchedule {
  const found = RAMADAN_2027_CALENDAR.find((d) => d.rozaNo === rozaNumber);
  return found || RAMADAN_2027_CALENDAR[0];
}

// Check if a given date falls within Ramadan 2027
export function isDateInRamadan2027(date: Date = new Date()): boolean {
  const y = date.getFullYear();
  const m = date.getMonth(); // 1 = Feb, 2 = Mar
  const d = date.getDate();

  if (y === 2027) {
    if (m === 1 && d >= 8) return true; // Feb 8-28
    if (m === 2 && d <= 9) return true; // Mar 1-9
  }
  return false;
}

