// Helper to add/subtract minutes from "HH:MM AM/PM"
function adjustTimeByMinutes(time12h: string, offsetMins: number): string {
  if (!time12h || offsetMins === 0) return time12h;
  const isPM = /PM/i.test(time12h);
  const cleaned = time12h.replace(/AM|PM/i, '').trim();
  const [hStr, mStr] = cleaned.split(':');
  let h = parseInt(hStr, 10);
  const m = parseInt(mStr, 10);
  if (isNaN(h) || isNaN(m)) return time12h;
  
  if (h === 12 && !isPM) h = 0;
  if (h < 12 && isPM) h += 12;
  
  let totalMins = (h * 60 + m + offsetMins + 1440) % 1440;
  const newH = Math.floor(totalMins / 60) % 24;
  const newM = totalMins % 60;
  const newAmpm = newH >= 12 ? 'PM' : 'AM';
  const newH12 = newH % 12 || 12;
  return `${newH12.toString().padStart(2, '0')}:${newM.toString().padStart(2, '0')} ${newAmpm}`;
}

// Get adjusted Sehri & Iftar timings based on selected Ramadan day and location
export function getAdjustedRamadanDay(
  rozaNumber: number = 1,
  locationId: string = 'north_karachi'
): RamadanDaySchedule {
  const baseDay = getRamadanDaySchedule(rozaNumber);
  const location = RAMADAN_LOCATIONS.find((l) => l.id === locationId) || RAMADAN_LOCATIONS[0];
  
  if (location.offsetMinutes === 0) {
    return baseDay;
  }
  
  return {
    ...baseDay,
    sehriEnd: adjustTimeByMinutes(baseDay.sehriEnd, location.offsetMinutes),
    fajrAzan: adjustTimeByMinutes(baseDay.fajrAzan, location.offsetMinutes),
    fajrJamaat: adjustTimeByMinutes(baseDay.fajrJamaat, location.offsetMinutes),
    sunrise: adjustTimeByMinutes(baseDay.sunrise, location.offsetMinutes),
    iftarTime: adjustTimeByMinutes(baseDay.iftarTime, location.offsetMinutes),
    maghribJamaat: adjustTimeByMinutes(baseDay.maghribJamaat, location.offsetMinutes),
    ishaAzan: adjustTimeByMinutes(baseDay.ishaAzan, location.offsetMinutes),
  };
}
